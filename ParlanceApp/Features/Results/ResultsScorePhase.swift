import SwiftUI

/// First-impression phase of the results flow: animated score ring, verdict
/// headline, prior-average delta, XP counter, and the "See Breakdown" CTA.
///
/// All animation/haptic state lives at the parent — this view only owns the
/// XP counter animation, which is intrinsic to the visuals here.
struct ResultsScorePhase: View {
    @Bindable var session: Session
    let cachedPriorAverage: Int?
    let cachedVerdictText: String
    @Binding var showXPBanner: Bool
    let onSeeBreakdown: () -> Void

    @State private var displayedXP: Int = 0
    @State private var xpAnimationTask: Task<Void, Never>? = nil

    var body: some View {
        VStack(spacing: 0) {
            Spacer()

            ScoreRingView(score: session.overallScore)
                .padding(.bottom, 20)

            Text(cachedVerdictText)
                .font(AppFonts.display(26))
                .foregroundStyle(AppColors.text)
                .multilineTextAlignment(.center)
                .padding(.horizontal, 32)

            if let avg = cachedPriorAverage {
                let delta = session.overallScore - avg
                HStack(spacing: 8) {
                    Text("Your average: \(avg)")
                        .font(AppFonts.body(12))
                        .foregroundStyle(AppColors.sub)
                    if delta != 0 {
                        Text("\(delta >= 0 ? "+" : "")\(delta)")
                            .font(AppFonts.bodyBold(11))
                            .foregroundStyle(delta >= 0 ? AppColors.teal : AppColors.red)
                            .padding(.horizontal, 8)
                            .padding(.vertical, 3)
                            .background((delta >= 0 ? AppColors.teal : AppColors.red).opacity(0.15))
                            .clipShape(Capsule())
                    }
                }
                .padding(.top, 8)
            }

            HStack(spacing: 6) {
                Image(systemName: "star.fill")
                    .font(.system(size: 14))
                    .foregroundStyle(AppColors.gold)
                Text("+\(displayedXP) XP")
                    .font(AppFonts.bodyBold(17))
                    .foregroundStyle(AppColors.gold)
            }
            .padding(.top, 20)
            .onAppear {
                SoundService.play(.xpEarned)
                xpAnimationTask = Task { await animateXP() }
            }
            .onDisappear {
                xpAnimationTask?.cancel()
                xpAnimationTask = nil
            }

            Spacer()

            Text("Score generated by AI · for practice only")
                .font(AppFonts.body(11))
                .foregroundStyle(AppColors.dim)
                .padding(.bottom, 4)

            Button(action: onSeeBreakdown) {
                Text("See Breakdown")
                    .font(AppFonts.bodyBold(16))
                    .foregroundStyle(AppColors.bg)
                    .frame(maxWidth: .infinity)
                    .padding(.vertical, 16)
                    .background(AppColors.gold)
                    .clipShape(RoundedRectangle(cornerRadius: AppConstants.cardRadius))
            }
            .padding(.horizontal, 32)
            .padding(.bottom, 48)
        }
        .onAppear {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.6) {
                withAnimation(.spring(response: 0.45, dampingFraction: 0.75)) {
                    showXPBanner = true
                }
            }
            DispatchQueue.main.asyncAfter(deadline: .now() + 3.8) {
                withAnimation(.easeOut(duration: 0.3)) {
                    showXPBanner = false
                }
            }
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity)
    }

    // MARK: - XP Animation

    private func animateXP() async {
        let target = session.xpEarned
        guard target > 0 else {
            displayedXP = 0
            return
        }
        let steps = 24
        for i in 1...steps {
            try? await Task.sleep(nanoseconds: 55_000_000)
            await MainActor.run {
                displayedXP = (target * i) / steps
            }
        }
        displayedXP = target
    }
}
